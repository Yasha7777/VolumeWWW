-- ============================================================
-- Миграция: EXIF кадра в colmap_photos (2026-08-23)
-- ------------------------------------------------------------
-- Запускать в: Supabase Dashboard → SQL Editor.
-- Безопасно катить на живой БД: только ADD COLUMN IF NOT EXISTS,
-- существующие данные не трогаются.
--
-- ЗАЧЕМ. n8n больше не получает фото байтами (поле photos_b64 убрано).
-- В вебхук уходят analysis_id, id строк colmap_photos, публичные ссылки
-- на оригиналы и EXIF; сами пиксели воркфлоу берёт из Storage по ссылке.
-- Пачка из 50 оригиналов давала ~250 МБ JSON — n8n на этом ложился.
--
-- EXIF при этом должен жить рядом с кадром, а не только в теле одного
-- запроса: по нему бэкенд считает качество кадра (ISO + BrightnessValue)
-- и выбирает 2 лучших для зрительной модели. Без этой колонки повторный
-- прогон (rerun) уходил в n8n с пустым EXIF, и «лучшими» становились
-- просто первые два кадра пачки.
--
-- ОТКУДА ДАННЫЕ: exifr на фронте (Analyze.jsx) парсит ОРИГИНАЛ до любой
-- конвертации (важно для HEIC — при конвертации EXIF теряется), фронт
-- шлёт массив exif_data параллельно файлам, бэкенд кладёт его сюда как
-- есть (см. analyses.py, _sanitize_exif).
--
-- Старые строки останутся с NULL — это штатно: кадр без EXIF получает
-- нейтральную оценку 0.5 и не выигрывает/не проигрывает отбор.
-- Бэкенд переживает и отсутствие этой колонки (пишет фото без EXIF и
-- ругается в лог), так что порядок «код → миграция» не ломает замеры.
-- ============================================================

ALTER TABLE public.colmap_photos
  ADD COLUMN IF NOT EXISTS exif JSONB;
