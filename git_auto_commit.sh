#!/bin/bash
# ─────────────────────────────────────────────────────────────────────────────
# Деплой фронта: собрать НА МАКЕ → проверить → закоммитить → запушить.
# На сервере остаётся только `git pull origin main && docker compose up --build -d`,
# npm там больше не запускается (см. frontend/Dockerfile).
#
# Почему сборка здесь, а не «когда вспомню»: образ раздаёт ровно тот dist/,
# что лежит в git. Забыл собрать перед коммитом — выкатил старый интерфейс,
# и понять это по логам деплоя невозможно, там всё зелёное.
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail
cd "$(dirname "$0")"

echo "▸ Собираю фронт (vite)…"
( cd frontend && npm run build )

# ── Защита от выката бандла с плейсхолдерами ────────────────────────────────
# Vite бакает VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY в момент сборки, из
# frontend/.env.local. Пока там лежали dev-заглушки, в git уезжал бандл с
# localhost:54321 — раньше это было безобидно (сервер пересобирал сам), теперь
# такой бандл уехал бы в прод и убил авторизацию. Проверяем артефакт, а не
# намерения.
if grep -rqE 'local-anon-placeholder|localhost:54321|127\.0\.0\.1:54321' frontend/dist/assets/ 2>/dev/null; then
  echo
  echo "✗ ОСТАНОВЛЕНО: в собранный dist попали dev-заглушки из frontend/.env.local."
  echo "  Пропиши туда БОЕВЫЕ значения и запусти скрипт заново:"
  echo "    VITE_SUPABASE_URL=https://<боевой-хост>"
  echo "    VITE_SUPABASE_ANON_KEY=<боевой anon-ключ>"
  echo "  (anon-ключ публичный по замыслу — он и так уезжает в бандл к каждому"
  echo "   пользователю. Секретный service-key сюда класть НЕЛЬЗЯ.)"
  echo "  Ничего не закоммичено."
  exit 1
fi

if [ ! -f frontend/dist/index.html ]; then
  echo "✗ ОСТАНОВЛЕНО: frontend/dist/index.html не найден — сборка не удалась."
  exit 1
fi

echo "▸ Бандл чистый, коммичу…"
git add . ':!3dmodels'

# Пересборка меняет хеши в именах чанков, так что «нечего коммитить» бывает
# редко — но если правок не было вовсе, не роняем скрипт с невнятной ошибкой
# (при set -e пустой git commit вернул бы 1 и оборвал всё до push).
if git diff --cached --quiet; then
  echo "▸ Изменений нет — коммитить нечего. Пушу то, что уже лежит локально."
else
  git commit -m "$(date +'%Y-%m-%d %H:%M:%S')"
fi

git push
echo "▸ Готово. На сервере: git pull origin main && docker compose up --build -d"
